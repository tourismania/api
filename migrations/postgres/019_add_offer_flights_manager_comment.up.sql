-- Комментарий менеджера к перелёту — необязательный текст для клиента.
-- «Комментария нет» хранится как '', а не NULL: в контракте отсутствие поля,
-- null и "" означают одно и то же, и один вид пустоты упрощает сравнение
-- наборов перелётов и чтение (поле всегда строка). Уже сохранённые перелёты
-- получают ''; константный DEFAULT не переписывает таблицу.
--
-- CHECK на длину нет намеренно: лимит (2000 символов) — правило формы запроса
-- и проверяется в presentation, как длина описания оффера; дубль в БД при
-- рассинхроне превращал бы ошибку клиента в 500.
ALTER TABLE offer_flights
    ADD COLUMN manager_comment TEXT NOT NULL DEFAULT '';
