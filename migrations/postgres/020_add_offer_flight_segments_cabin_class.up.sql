-- Класс обслуживания сегмента перелёта (economy, comfort, comfort_plus,
-- business) — необязателен: при составлении предложения он может быть ещё
-- неизвестен. '' — «класс неизвестен», а не бизнес-умолчание: значение по
-- умолчанию за клиента не подставляется. DEFAULT '' нужен, чтобы уже
-- сохранённые сегменты получили «неизвестен», а старый код, вставляющий
-- сегменты без столбца, продолжал работать; константный DEFAULT не
-- переписывает таблицу.
--
-- '' вместо NULL — как у offer_flights.manager_comment: в контракте
-- отсутствие поля, null и "" означают одно и то же, и один вид пустоты
-- упрощает сравнение наборов перелётов и чтение (поле всегда строка).
--
-- CHECK и PostgreSQL ENUM на значения нет намеренно: набор классов — доменное
-- правило (flight.CabinClasses), он расширяется по решению продукта; дубль в
-- БД требовал бы синхронной миграции и превращал рассинхрон в 500.
-- См. docs/cabin-classes.md.
ALTER TABLE offer_flight_segments
    ADD COLUMN cabin_class VARCHAR(16) NOT NULL DEFAULT '';
