// Package helpers содержит общие помощники слоя хранения, не привязанные к
// одному репозиторию.
package helpers

import "strings"

// EscapeLike делает строку буквальной внутри шаблона LIKE: `%`, `_` и `\`
// перестают быть подстановкой и экранированием. Подстановочные `%` по краям
// шаблона вызывающий добавляет сам, уже после экранирования.
//
// Опирается на экранирующий символ `\` по умолчанию у LIKE (так в
// PostgreSQL; в запросах нет ESCAPE): если добавить ESCAPE с другим
// символом, экранирование нужно менять вместе с ним.
func EscapeLike(s string) string {
	// Replacer проходит строку один раз, поэтому вставленные `\` повторно не
	// экранируются и порядок пар не важен.
	return strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`).Replace(s)
}
