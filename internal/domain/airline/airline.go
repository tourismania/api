// Package airline — справочник авиакомпаний (travel-services/airlines):
// сущность Airline со страной, служебная запись «Неизвестная», фильтр поиска
// и контракт репозитория для поиска, проверки ссылок сегментов перелётов и
// синхронизации из источника. Ключ авиакомпании — собственный id записи, а
// коды ICAO и IATA — атрибуты без уникальности: коды переназначаются после
// закрытия авиакомпаний и встречаются у нескольких записей источника.
// Пакет ни от кого не зависит: страна — своя структура, а не airport.Country.
package airline

import "time"

// UnknownID — id служебной записи «Неизвестная» (Unknown): её выбирают для
// сегмента, перевозчик которого ещё неизвестен. Значение фиксировано — это
// контракт для клиентов api и DEFAULT в миграции 022; запись создаёт
// миграция 021, синхронизация её не меняет.
const UnknownID = 1

// Country — страна авиакомпании: код ISO 3166-1 alpha-2 и название из
// общего со справочником аэропортов списка стран.
type Country struct {
	ISO2 string
	Name string
}

// Airline — авиакомпания справочника. ICAO nil только у служебной записи.
// NameRU — русское название, только у авиакомпаний России ("" — нет).
// Country nil — страна в источнике не указана или неоднозначна. DissolvedOn
// nil — авиакомпания действует. IATACodes — все коды IATA из источника
// (наружу api их не отдаёт). Hidden — запись скрыта из поиска: дубль,
// слитый в источнике с другой авиакомпанией, или пропавшая из источника;
// на неё можно ссылаться только из оффера, который уже ссылался на неё.
type Airline struct {
	ID          int
	ICAO        *string
	Name        string
	NameRU      string
	Country     *Country
	DissolvedOn *time.Time
	IATACodes   []string
	Hidden      bool
}

// Filter — нормализованные параметры поиска. Search — подстрока названия
// авиакомпании или страны ("" допустимо только вместе с IDs); CountryISO2 —
// код страны заглавными буквами ("" — без отбора); IDs — отбор по id
// (пусто — без отбора). Скрытые записи поиск не возвращает никогда.
type Filter struct {
	Search      string
	CountryISO2 string
	IDs         []int
	Limit       int
	Offset      int
}

// SearchResult — страница найденных авиакомпаний и их общее число без
// учёта пагинации.
type SearchResult struct {
	Airlines   []Airline
	TotalCount int64
}

// SourceRecord — запись справочника, загруженная из источника, с её
// состоянием в источнике: Merged — дубль (merged_into_id заполнен),
// Missing — пропала из источника (missing_since заполнен).
type SourceRecord struct {
	ID      int
	Merged  bool
	Missing bool
}
