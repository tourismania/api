// Package syncairlines — команда синхронизации справочника авиакомпаний из
// Wikidata (CLI `airlines sync`): разбор данных источника, запись стран и
// авиакомпаний, пометка дублей и пропавших, журнал аномалий источника.
package syncairlines

import "io"

// Command — параметры синхронизации.
type Command struct {
	// DryRun — выполнить запросы к источнику, разбор и журнал аномалий, но
	// ничего не записывать в справочник.
	DryRun bool

	// Progress, если не nil, получает строки прогресса и итог для оператора.
	Progress io.Writer
}
